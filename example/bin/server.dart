import 'dart:async';

import 'package:gisila/gisila.dart';
import 'package:gisila_example/controllers/users_controller.dart';
import 'package:gisila_example/services/user_service.dart';

Future<void> main(List<String> args) async {
  final app = GisilaApp(
    config: AppConfig(
      logLevel: LogLevel.info,
      logFormat: LogFormat.text,
      logRequests: true,
      requestIdHeader: 'X-Request-Id',
      cors: const CorsConfig(),
      // App-wide defaults that every route inherits unless overridden
      // by a method-level `config:` parameter.
      defaultRouteConfig: const RouteConfig(
        rateLimit: RateLimitConfig(requestsPerMinute: 300),
        timeout: Duration(seconds: 15),
      ),
      authenticator: const StaticTokenAuthenticator(<String, Principal>{
        'admin-token': Principal(
          id: 'admin',
          roles: {'admin'},
          permissions: {'users:read', 'users:write'},
        ),
        'reader-token': Principal(
          id: 'reader',
          permissions: {'users:read'},
        ),
        'writer-token': Principal(
          id: 'writer',
          permissions: {'users:write'},
        ),
      }),
    ),
  );

  // Reject POST/PUT/PATCH with unsupported Content-Types globally.
  app.use(allowedContentTypesMiddleware());

  // Register one Service factory per service class - the framework
  // materialises a fresh instance per request, attaches the
  // RequestContext, and injects it into controller methods that
  // declare a `UserService` parameter.
  app.registerService<UserService>(UserService.new);

  // `attachToApp` is generated by build_runner.
  final users = UsersController();
  app.registerController(attacher: users.attachToApp);

  await app.start(host: '0.0.0.0', port: 8080);
  print('Try: curl -H "Authorization: Bearer reader-token" '
      'http://localhost:8080/users/me');
}
